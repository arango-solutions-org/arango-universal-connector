"""Generate the Python gRPC stubs for the Links runtime from the vendored protos.

The protos in ``packages/links/proto`` are copied from kube-arangodb at the version in
``KUBE_ARANGODB_VERSION``. Run ``make protos`` after updating them; the generated code is
committed so builds don't need the protobuf toolchain.

protoc writes modules named after the proto paths (``integrations.link.v1...``); they are
rewritten into ``arango_connector_links._pb`` so they don't claim a top-level package.
"""

from __future__ import annotations

import os
import re
import shutil
import sys
from pathlib import Path

import google.api.annotations_pb2
import grpc_tools
from grpc_tools import protoc

ROOT = Path(__file__).resolve().parents[1]
PROTO_DIR = ROOT / "packages/links/proto"
OUT = ROOT / "packages/links/src/arango_connector_links/_pb"
PACKAGE = "arango_connector_links._pb"


def main() -> int:
    protos = sorted(str(p.relative_to(PROTO_DIR)) for p in PROTO_DIR.rglob("*.proto"))
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    includes = [
        PROTO_DIR,
        # google/api/annotations.proto ships with googleapis-common-protos
        Path(os.path.dirname(google.api.annotations_pb2.__file__)).parents[1],
        # google/protobuf/*.proto ship with grpcio-tools
        Path(os.path.dirname(grpc_tools.__file__)) / "_proto",
    ]
    args = [
        "protoc",
        *(f"-I{path}" for path in includes),
        f"--python_out={OUT}",
        f"--pyi_out={OUT}",
        f"--grpc_python_out={OUT}",
        *protos,
    ]
    if protoc.main(args) != 0:
        print("protoc failed", file=sys.stderr)
        return 1

    for path in OUT.rglob("*.py*"):
        text = path.read_text()
        text = re.sub(r"^from integrations\.", f"from {PACKAGE}.integrations.", text, flags=re.M)
        text = re.sub(
            r"^import integrations\.", f"import {PACKAGE}.integrations.", text, flags=re.M
        )
        path.write_text(text)
    for directory in [OUT, *(p for p in OUT.rglob("*") if p.is_dir())]:
        (directory / "__init__.py").touch()
    (OUT / "__init__.py").write_text(
        '"""Generated by tools/gen_protos.py from packages/links/proto. Do not edit."""\n'
    )
    version = (PROTO_DIR / "KUBE_ARANGODB_VERSION").read_text().strip()
    print(f"generated {len(protos)} protos (kube-arangodb {version}) into {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
